// Optional real-browser QA. All server data is disposable, outside the checkout.
const { chromium } = require('playwright');
const { spawn } = require('node:child_process');
const path = require('node:path');
const fs = require('node:fs');
const assert = require('node:assert/strict');
const root = path.resolve(__dirname, '..');
const checks = [];
const check = (value, name) => { assert.ok(value, name); checks.push(name); console.log('PASS', name); };
(async () => {
  const server = spawn(process.env.CS_PYTHON || 'python3', [path.join(__dirname, 'run_mock_api_fixture.py')], { cwd: root });
  let browser;
  try {
    const base = await new Promise((resolve, reject) => {
      let output = '';
      const timer = setTimeout(() => reject(Error('HTTP fixture startup timed out')), 15000);
      server.stdout.on('data', (chunk) => { output += chunk; if (output.includes('\n')) { clearTimeout(timer); resolve(output.trim().split('\n')[0]); } });
      server.on('error', reject);
      server.on('exit', (code) => { clearTimeout(timer); reject(Error('HTTP fixture exited: ' + code)); });
      server.stderr.on('data', (chunk) => process.stderr.write(chunk));
    });
    browser = await chromium.launch({ headless: true, executablePath: process.env.CS_CHROMIUM_PATH || undefined });
    const context = await browser.newContext({ viewport: {width: 1440, height: 1000}, locale: 'vi-VN' });
    const page = await context.newPage();
    page.setDefaultTimeout(12000);
    const errors = [];
    page.on('pageerror', (error) => errors.push(error.message));
    await page.goto(base + '/html/shared/api-demo.html');
    await page.locator('.api-project').first().waitFor();
    const initial = await page.locator('.api-project').count();
    check(initial >= 2 && (await page.locator('#connection').textContent()).includes('Đã kết nối'), 'GET list renders seeded projects from real HTTP');
    await page.evaluate(() => localStorage.setItem('creatorstudio.team.v1', 'qa-sentinel'));
    await page.locator('#create').click();
    await page.locator('#name').fill('Dự án kiểm thử HTTP');
    await page.locator('#deadline').fill('2026-12-20');
    await page.locator('#description').fill('Tiếng Việt: thương hiệu sáng tạo.');
    const creation = page.waitForResponse((response) => response.request().method() === 'POST');
    await page.locator('#save').click();
    check(await page.locator('#save').isDisabled(), 'Save button blocks duplicate requests during latency');
    const created = await (await creation).json();
    await page.locator('#editor').waitFor({state:'hidden'});
    check((await page.locator('.api-project').count()) === initial + 1, 'POST 201 adds a project only after server success');
    await page.reload();
    await page.locator(`[data-edit="${created.id}"]`).waitFor();
    check(true, 'Created project persists after browser reload');
    const second = await context.newPage();
    second.on('pageerror', (error) => errors.push(error.message));
    await second.goto(base + '/html/shared/api-demo.html');
    await second.locator(`[data-edit="${created.id}"]`).waitFor();
    check(true, 'Second tab sees shared server data');
    await page.locator(`[data-edit="${created.id}"]`).click();
    await page.locator('#editor').waitFor({state:'visible'});
    await second.locator(`[data-edit="${created.id}"]`).click();
    await second.locator('#editor').waitFor({state:'visible'});
    await page.locator('#name').fill('Tab A đã cập nhật');
    await page.locator('#save').click();
    await page.locator('#editor').waitFor({state:'hidden'});
    await second.locator('#name').fill('Tab B không được ghi đè');
    const conflict = second.waitForResponse((response) => response.request().method() === 'PATCH');
    await second.locator('#save').click();
    check((await conflict).status() === 412, 'Stale PATCH receives real HTTP 412');
    await second.locator('#editor-error').filter({hasText:'tab khác'}).waitFor();
    check((await second.locator('#name').inputValue()) === 'Tab B không được ghi đè', 'Conflict retains unsaved form text');
    await second.locator('#cancel-editor').click();
    await second.close();
    await page.locator('#create').click();
    await page.locator('#name').fill('Dự án thử lỗi và thử lại');
    await page.locator('#deadline').fill('2026-12-21');
    await page.locator('#fail-save').check();
    const failure = page.waitForResponse((response) => response.request().method() === 'POST');
    await page.locator('#save').click();
    check((await failure).status() === 503, 'Failure checkbox triggers a real HTTP 503');
    await page.locator('#editor-error').filter({hasText:'503'}).waitFor();
    check((await page.locator('#name').inputValue()) === 'Dự án thử lỗi và thử lại' && !(await page.locator('#fail-save').isChecked()), 'Failed save retains content and resets one-shot failure');
    const retry = page.waitForResponse((response) => response.request().method() === 'POST');
    await page.locator('#save').click();
    check((await retry).status() === 201, 'Retry succeeds without duplicate failed data');
    await page.locator('#editor').waitFor({state:'hidden'});
    await page.locator(`[data-delete="${created.id}"]`).click();
    const deletion = page.waitForResponse((response) => response.request().method() === 'DELETE');
    await page.locator('#confirm-delete').click();
    check((await deletion).status() === 204, 'Confirmed delete returns HTTP 204');
    await page.locator('#delete-dialog').waitFor({state:'hidden'});
    check((await page.locator(`[data-delete="${created.id}"]`).count()) === 0, 'Deleted project disappears after server acknowledgement');
    check((await page.evaluate(() => localStorage.getItem('creatorstudio.team.v1'))) === 'qa-sentinel', 'API demo never modifies the team Store');
    check((await page.locator('#request-log li').count()) <= 8, 'HTTP log stays bounded');
    if (process.env.CS_QA_SCREENSHOTS) fs.mkdirSync(process.env.CS_QA_SCREENSHOTS, {recursive:true});
    for (const width of [360, 390, 768, 1440]) {
      await page.setViewportSize({width, height:900});
      await page.evaluate(() => document.fonts.ready);
      check(!(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)), 'No page overflow at ' + width + 'px');
      await page.locator('#create').click();
      await page.locator('#editor').waitFor({state:'visible'});
      check(!(await page.locator('#editor').evaluate((el) => el.scrollWidth > el.clientWidth)), 'Editor fits at ' + width + 'px');
      await page.keyboard.press('Escape');
      check(!(await page.locator('#editor').isVisible()), 'Native Escape closes editor at ' + width + 'px');
      if (process.env.CS_QA_SCREENSHOTS) await page.screenshot({path:path.join(process.env.CS_QA_SCREENSHOTS, 'mock-api-' + width + '.png'),fullPage:true});
    }
    check(errors.length === 0, 'No browser JavaScript errors');
    const report = {passed:checks.length, browser:browser.version(), checks, testedBase:process.env.CS_TESTED_BASE || 'working-tree'};
    if (process.env.CS_TEST_REPORT) fs.writeFileSync(process.env.CS_TEST_REPORT, JSON.stringify(report,null,2));
    console.log('TOTAL', checks.length, 'real-browser checks passed');
  } finally {
    if (browser) await browser.close();
    server.kill('SIGTERM');
  }
})().catch((error) => { console.error(error); process.exitCode=1; });
